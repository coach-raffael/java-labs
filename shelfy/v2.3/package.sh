#!/usr/bin/env bash
# shelfy 2.3 (Module 17): from the JAR to a runtime of your own and a native package.
# Run after ./mvnw verify from this directory:  ./package.sh
# Needs JDK 25 (jdeps, jlink, jpackage) and, for RPM or DEB, rpm-build (Rocky, Alma) or fakeroot (Ubuntu).
# On macOS and in Codespaces only the app image is built.
set -eu
cd "$(dirname "$0")"
JAR=target/dist/shelfy-2.3.0.jar
if [ ! -f "$JAR" ]; then
  echo "Build first: ./mvnw verify"
  exit 1
fi

echo "== 1. Which modules does shelfy need? (jdeps)"
MODULES="$(jdeps --multi-release 25 --print-module-deps --ignore-missing-deps "$JAR" target/dist/lib/*.jar)"
echo "$MODULES"

echo "== 2. A runtime with exactly these modules (jlink)"
rm -rf target/runtime
jlink --add-modules "$MODULES" --strip-debug --no-man-pages --no-header-files --compress zip-6 --output target/runtime
du -sh target/runtime
target/runtime/bin/java -version

echo "== 3. An application image with its own runtime (jpackage)"
rm -rf target/pkg
jpackage --type app-image --input target/dist --main-jar shelfy-2.3.0.jar --main-class shelfy.Main \
  --name shelfy --app-version 2.3.0 --runtime-image target/runtime --dest target/pkg
du -sh target/pkg/shelfy
echo "Start it with: target/pkg/shelfy/bin/shelfy serve"

echo "== 4. A native package for this Linux, built from the app image (jpackage)"
# jpackage prints "Warning: app-image dir not generated by jpackage." here (JDK 25); the package is fine.
case "$(uname -s)" in
  Linux)
    if command -v rpmbuild >/dev/null 2>&1; then
      jpackage --type rpm --app-image target/pkg/shelfy --name shelfy --app-version 2.3.0 --dest target/pkg \
        --description "shelfy, the library of the course Java Programming Fundamentals" --vendor "Raffael Huehnerschulte"
      ls -l target/pkg/*.rpm
      echo "Install with: sudo rpm -i target/pkg/shelfy-2.3.0-1.x86_64.rpm   (remove: sudo rpm -e shelfy)"
    elif command -v fakeroot >/dev/null 2>&1; then
      jpackage --type deb --app-image target/pkg/shelfy --name shelfy --app-version 2.3.0 --dest target/pkg \
        --description "shelfy, the library of the course Java Programming Fundamentals" --vendor "Raffael Huehnerschulte" \
        --linux-deb-maintainer "coach-raffael@users.noreply.github.com"
      ls -l target/pkg/*.deb
      echo "Install with: sudo apt install ./target/pkg/shelfy_2.3.0_amd64.deb   (remove: sudo apt remove shelfy)"
    else
      echo "Neither rpmbuild nor fakeroot found: install rpm-build (dnf) or fakeroot (apt) for a native package."
    fi
    ;;
  *)
    echo "Not Linux: the app image in target/pkg/shelfy is your package here."
    ;;
esac
echo "After the installation the command is /opt/shelfy/bin/shelfy (the package creates no link in /usr/bin)."
